import { URL } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { normalize, fingerprint } from '../src/core.ts';
import type { Seed, Review, Status } from '../src/types.ts';

function obj(value: unknown): Record<string, unknown> {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error('Invalid seed input');
  return value as Record<string, unknown>;
}
function str(value: unknown): string { if (typeof value !== 'string') throw new Error('Invalid seed string'); return value; }
const root = new URL('../../../', import.meta.url);
const catalogBytes = await readFile(new URL('provenance/security-advisories-20261114.json', root));
const catalogInput = obj(JSON.parse(catalogBytes.toString()) as unknown);
const ledger = obj(JSON.parse(await readFile(new URL('evidence/security-coverage-20261114.json', root), 'utf8')) as unknown);
const inputs = obj(JSON.parse(await readFile(new URL('provenance/inputs.json', root), 'utf8')) as unknown);
if (ledger.catalog_sha256 !== createHash('sha256').update(catalogBytes).digest('hex')) throw new Error('Seed catalog identity differs from reviewed ledger');
const sourceHash = str(ledger.candidate_source_sha256);
if (!/^[a-f0-9]{64}$/.test(sourceHash) || sourceHash !== inputs.normalized_candidate_sha256) throw new Error('Seed source identity mismatch');
if (!Array.isArray(catalogInput.entries) || !Array.isArray(ledger.entries)) throw new Error('Missing seed catalog/assessments');
const catalog = catalogInput.entries.map(normalize).sort((a, b) => a.ghsa_id.localeCompare(b.ghsa_id));
const byId = new Map(catalog.map(a => [a.ghsa_id, a]));
const reviews: Review[] = [];
for (const entry of ledger.entries) {
  const row = obj(entry); const id = str(row.ghsa_id); const advisory = byId.get(id);
  if (!advisory || row.cve_id !== advisory.cve_id) throw new Error('Seed assessment identity mismatch');
  const status = str(row.status);
  if (!['RESOLVED', 'NOT_APPLICABLE', 'PLANNED'].includes(status)) throw new Error('Invalid reviewed status');
  reviews.push({ id, upstreamHash: await fingerprint(advisory), sourceHash, status: status as Status,
    component: str(row.component), reason: str(row.reason_en), action: str(row.planned_action_en), validation: str(row.validation) });
}
if (reviews.length !== catalog.length || new Set(reviews.map(r => r.id)).size !== catalog.length) throw new Error('Incomplete seed coverage');
const seed: Seed = { schema: 1, sourceHash, catalog, reviews: reviews.sort((a, b) => a.id.localeCompare(b.id)) };
const output = "// Generated by scripts/build-seed.ts from the reviewed public catalog and ledger.\nimport type { Seed } from './types.ts';\nconst seed = " + JSON.stringify(seed, null, 2) + " satisfies Seed;\nexport default seed;\n";
await writeFile(new URL('../src/seed.ts', import.meta.url), output);
console.log(JSON.stringify({ seeded: catalog.length, sourceHash }));
