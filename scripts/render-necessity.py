#!/usr/bin/env python3
"""Render the source-bound implementation-necessity review without fixed credit."""
import argparse
from collections import Counter
import html
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from patchkit.coverage import validate_necessity

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
review = json.loads((root / 'evidence/implementation-necessity-20261114.json').read_text())
ledger = json.loads((root / 'evidence/security-coverage-20261114.json').read_text())
counts = validate_necessity(ledger, review)
source_counts = Counter(row['shipped_source_action'] for row in review['entries'])


def cell(value):
    return html.escape(str(value), quote=False).replace('|', '\\|').replace('\n', ' ')


for lang in ('en', 'ko'):
    ko = lang == 'ko'
    labels = {'REQUIRED': '수정 필요' if ko else 'Implementation required',
              'CONDITIONAL': '조건 확인 후 결정' if ko else 'Decide after prerequisites',
              'OUTSIDE_LINUX_FPM': '다른 OS·SAPI 전용' if ko else 'Different OS/SAPI',
              'MECHANISM_ABSENT': '해당 결함 경로 없음' if ko else 'Exact mechanism absent',
              'ALREADY_COVERED': '기존 보호 포함' if ko else 'Protection already present'}
    actions = {'REQUIRED': '필요' if ko else 'Required', 'CONDITIONAL': '조건부' if ko else 'Conditional',
               'NONE': '해당 공지 수정 불필요' if ko else 'No change for this advisory'}
    other = 'IMPLEMENTATION_NECESSITY.md' if ko else 'IMPLEMENTATION_NECESSITY.ko.md'
    lines = ['# ' + ('실제 구현 필요성 판정' if ko else 'Actual implementation necessity'), '',
             '[English / 한국어](' + other + ')', '',
             '<!-- Generated by scripts/render-necessity.py from source-bound review data. -->', '',
             ('**기존 구현 예정 51건을 먼저 대조한 판정입니다. 51건 전부를 현재 Linux FPM의 확정 취약점이나 필수 패치로 취급하지 않습니다.**' if ko else
              '**This reviews the original 51 planned items before implementation. They are not 51 confirmed vulnerabilities or mandatory patches in the current Linux FPM artifact.**'), '',
             '| ' + ('현재 공개 Xenial FPM 기준 | 건수' if ko else 'Published Xenial FPM scope | Count') + ' |', '|---|---|']
    for decision, label in labels.items():
        lines.append('| ' + label + ' | ' + str(counts[decision]) + ' |')
    if ko:
        lines += ['', '## 판정 범위와 원칙', '',
                  '- 기준은 공개한 Xenial x86-64 FPM 빌드·고정 PHP 소스입니다. 실제 운영 서버의 활성 모듈·설정·애플리케이션 노출은 조회하지 않았습니다.',
                  '- 수정 필요는 해당 구성요소와 결함 경로가 존재한다는 뜻입니다. 응용 함수·설정의 사용 조건을 함께 적었으며 인터넷에서 바로 공격 가능하다는 뜻은 아닙니다.',
                  '- 조건부는 선택 모듈·연결 라이브러리·플랫폼 또는 다른 결함 경로의 전제를 먼저 확정해야 합니다. 조건이 성립하지 않는 배포에 패치를 강요하지 않습니다.',
                  f'- 전체 배포 소스에서는 **{source_counts["REQUIRED"]}건의 보호 누락을 확인했고, {source_counts["CONDITIONAL"]}건은 추가 조건 판단, {source_counts["NONE"]}건은 해당 공지의 수정이 불필요**합니다. 선택 모듈을 빌드하지 않은 것은 그 모듈 소스를 고쳤다는 뜻이 아닙니다.',
                  '- JPEG CVE-2025-14177의 정확한 결함 helper는 PHP 7.0에 없습니다. 기존 판정을 정정해 전체 공식 대응표는 수정 구현 2 / 해당 경로 부재 14 / 검토·구현 예정 50건입니다. 이전 판정은 ledger의 prior_assessment와 Git 이력에 보존했습니다.',
                  '- 별도의 오래된 APPn short-read 우려, FPM NUL 로그 처리, Firebird의 다른 NUL 처리 경로를 동일 CVE의 필수 수정으로 합치지 않습니다. 각각 필요한 검토 조건과 다음 확인을 기록했습니다.',
                  '- 이 변경은 필요성 판정입니다. PHP 수정 코드·서버 배포·공격 차단 시험 결과를 추가한 것이 아닙니다.', '',
                  '## 소스 근거와 검증', '']
    else:
        lines += ['', '## Scope and decision rules', '',
                  '- The target is the published Xenial x86-64 FPM build and pinned PHP source. No live server module/configuration/application exposure was inspected.',
                  '- Required means the component and reported source gap are established. Function/configuration use remains an explicit prerequisite, not proof of internet exploitability.',
                  '- Conditional requires the named module, library, platform or materially different mechanism to be settled before patching. An inapplicable deployment must not be forced through that patch.',
                  f'- Across the complete shipped source, **{source_counts["REQUIRED"]} protection gaps are established, {source_counts["CONDITIONAL"]} require further prerequisite decisions and {source_counts["NONE"]} needs no change for the exact advisory**. Omitting a module from a build does not fix its source.',
                  '- The exact later JPEG helper mechanism of CVE-2025-14177 is absent in PHP 7.0. Corrected catalog counts are 2 implemented / 14 mechanism-absent / 50 review-or-implementation planned. The prior assessment remains in the ledger and Git history.',
                  '- Distinct APPn short-read concerns, legacy FPM NUL logging and older Firebird NUL paths are not silently converted into mandatory fixes for different CVE mechanisms. Concrete next checks are retained separately.',
                  '- This is an applicability assessment, not new PHP protection code, server deployment or exploit-blocking evidence.', '',
                  '## Source evidence and validation', '']
    lines += ['- Candidate source SHA-256: `' + review['candidate_source_sha256'] + '`',
              '- [Full assessment, prerequisites, next checks and file hashes](../evidence/implementation-necessity-20261114.json)',
              '- [Exact Xenial crypt backend evidence](../evidence/xenial-crypt-backend-20261114.json) · [Build identity](../evidence/xenial-build-20261114.json)',
              '- [Complete official coverage](SECURITY_COVERAGE' + ('.ko' if ko else '') + '.md)', '',
              ('공식 수정 diff·전후 release 코드와 PHP 7.0의 실제 호출 경로를 대조했습니다. 아래 소스 참조는 위 해시의 준비 소스 기준입니다. 내장 bcrypt 경로는 공개 바이너리와 일치하는 ELF 심볼·조건부 소스 편입으로 확인했으며 바이너리를 실행하지 않았습니다.' if ko else
               'Official fix diffs/release code were compared with actual PHP 7.0 call chains. Source references address the pinned prepared tree. Bundled bcrypt selection was established through matching published ELF hashes, defined symbols and conditional source inclusion without executing the binaries.'), '',
              '## ' + ('항목별 판정' if ko else 'Per-advisory decisions'), '',
              '| ' + ('공지 · 구성요소 | 현재 대상 / 전체 소스 | 이유 · 조건 | 근거' if ko else 'Advisory / component | Target / shipped source | Reason / prerequisites | Evidence') + ' |', '|---|---|---|---|']
    for row in review['entries']:
        url = 'https://github.com/php/php-src/security/advisories/' + row['id']
        issue = '[' + cell(row.get('cve_id') or row['id']) + '](' + url + ')<br>' + cell(row['id']) + '<br>' + cell(row['component'])
        decision = '**' + labels[row['decision']] + '**<br>' + ('전체 소스: ' if ko else 'Shipped source: ') + actions[row['shipped_source_action']]
        evidence = '<br>'.join('`' + cell(ref) + '`' for ref in row['candidate_evidence'])
        evidence += '<br>' + ' · '.join('[official ' + str(i) + '](' + url + ')' for i, url in enumerate(row['official_sources'], 1))
        lines.append('| ' + issue + ' | ' + decision + ' | ' + cell(row['reason_' + lang]) + ' | ' + evidence + ' |')
    lines += ['', '## ' + ('구현 순서' if ko else 'Implementation order'), '',
              ('1. 수정 필요로 확정된 FPM 접근제어·요청 파싱·쿠키 경계와 상태 출력부터 처리합니다.\n2. HTTP 헤더·리다이렉트·네트워크 문자열 처리는 같은 파일의 변경을 함께 검토합니다. TLS 이름 검증·bcrypt·필터 보호도 해당 빌드에서 확인한 경로부터 진행합니다.\n3. 선택 모듈·라이브러리 조건은 항목별로 먼저 닫고, Windows/CGI/개발 서버는 별도 대상으로 유지합니다.\n4. 각 구현은 정상 동작과 보안 회귀의 의미 있는 검증을 거친 뒤에만 해결됨으로 바꿉니다.' if ko else
               '1. Start with confirmed FPM access control, request parsing, cookie boundaries and status output.\n2. Review interacting HTTP header/redirect/network-string changes together; handle TLS identity, bcrypt and filters in their admitted build paths.\n3. Close optional-module/library prerequisites first; keep Windows/CGI/development-server work separate.\n4. Credit implementation only after meaningful normal-behavior and security regression evidence.'), '']
    result = '\n'.join(lines)
    path = root / ('docs/IMPLEMENTATION_NECESSITY' + ('.ko' if ko else '') + '.md')
    if args.check:
        if path.read_text() != result:
            raise SystemExit('stale necessity document: ' + str(path.relative_to(root)))
    else:
        path.write_text(result)
print('Necessity documents ' + ('match' if args.check else 'rendered') + ' for 51 original planned advisories.')
