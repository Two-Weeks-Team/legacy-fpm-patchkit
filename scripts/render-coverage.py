#!/usr/bin/env python3
"""Render bilingual coverage documentation from the reviewed, versioned ledger."""
import argparse
import html
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from patchkit.coverage import validate, validate_necessity

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='check exact rendering without writing')
args = parser.parse_args()
catalog = json.loads((root / 'provenance/security-advisories-20261114.json').read_text())
ledger = json.loads((root / 'evidence/security-coverage-20261114.json').read_text())
counts = validate(catalog, ledger)
necessity_path = root / 'evidence/implementation-necessity-20261114.json'
necessity = json.loads(necessity_path.read_text()) if necessity_path.exists() else None
necessity_counts = validate_necessity(ledger, necessity) if necessity else None
by_id = {r['ghsa_id']: r for r in catalog['entries']}


def code(value):
    return str(value).replace('`', '').replace('|', '\\|').replace('\n', ' ')


def cell(value):
    return html.escape(str(value), quote=False).replace('|', '\\|').replace('\n', '<br>')


for lang in ('en', 'ko'):
    ko = lang == 'ko'
    labels = {'RESOLVED': '해결됨 · 수정 구현' if ko else 'Resolved · implemented',
              'NOT_APPLICABLE': '영향 없음 · 해당 결함 경로 부재' if ko else 'Not applicable · mechanism absent',
              'PLANNED': '미해결 · 검토·구현 예정' if ko else 'Unresolved · review/implementation planned'}
    title = '공식 공개 취약점 대응 현황' if ko else 'Official advisory coverage'
    other = 'SECURITY_COVERAGE.md' if ko else 'SECURITY_COVERAGE.ko.md'
    lines = ['# ' + title, '', '[English / 한국어](' + other + ')', '',
             '<!-- Generated by scripts/render-coverage.py; edit the reviewed ledger, not this table. -->',
             '<!-- COVERAGE_COUNTS: ' + json.dumps(counts, sort_keys=True) + ' -->', '']
    if ko:
        lines += [f'**2026-11-14 기준 공식 PHP 저장소 공지 {len(by_id)}건 전수 대응표입니다.** 기존 Ubuntu 보안 패치의 CVE {counts["VENDOR_RESOLVED"]}건은 아래에 별도로 표시합니다. 미구현 보호는 해결된 것으로 집계하지 않습니다.', '',
                  '| 공식 목록 내 상태 | 건수 |', '|---|---|']
    else:
        lines += [f'**Complete accounting of the {len(by_id)} published official PHP repository advisories as of 2026-11-14.** The {counts["VENDOR_RESOLVED"]} CVEs named by active Ubuntu vendor security patches are listed separately below. Unimplemented protections receive no fixed credit.', '',
                  '| Official catalog status | Count |', '|---|---|']
    for status in labels:
        lines.append('| ' + labels[status] + ' | ' + str(counts[status]) + ' |')
    if necessity_counts:
        doc = 'IMPLEMENTATION_NECESSITY' + ('.ko' if ko else '') + '.md'
        lines += ['', (f'기존 51건의 [실제 구현 필요성 판정]({doc}): 공개 Xenial FPM 기준 수정 필요 {necessity_counts["REQUIRED"]} / 조건 확인 후 결정 {necessity_counts["CONDITIONAL"]} / 다른 OS·SAPI 전용 {necessity_counts["OUTSIDE_LINUX_FPM"]} / 해당 결함 경로 없음 {necessity_counts["MECHANISM_ABSENT"]}건입니다. 구현 예정 전체를 현재 FPM의 확정 취약점으로 해석하지 않습니다.' if ko else
                       f'[Actual implementation necessity]({doc}) for the original 51 items: {necessity_counts["REQUIRED"]} required in the published Xenial FPM scope / {necessity_counts["CONDITIONAL"]} prerequisite-dependent / {necessity_counts["OUTSIDE_LINUX_FPM"]} other OS/SAPI / {necessity_counts["MECHANISM_ABSENT"]} exact mechanism absent. Planned items are not all confirmed vulnerabilities in this FPM artifact.')]
    if ko:
        lines += ['', '## 판정 기준과 대상', '',
                  '- **해결됨:** 이 배포 소스에 해당 수정 구현이 있습니다. 소스 검증과 실제 공격 차단 실증은 별개이며, `source-only`를 보안 시험 통과로 읽으면 안 됩니다.',
                  '- **영향 없음:** 해당 공지의 구체적 결함 경로가 PHP 7.0에 없다는 소스·도입 이력 근거가 있습니다. 버전이 오래됐거나 시험 빌드에 확장 모듈이 없다는 이유로 이 판정을 하지 않습니다.',
                  '- **미해결·구현 예정:** 이 릴리스에서 해당 보호를 제공한다고 인정하지 않습니다. 필요한 조사·보호 이식·회귀검증을 항목별로 명시합니다. 이는 최신 PHP용 공격이 PHP 7.0에서도 그대로 성립한다는 단정과 다릅니다. 라이브러리·플랫폼 조건을 확정하는 작업도 구현 계획에 포함합니다.',
                  '- 대상은 고정된 전체 배포 소스입니다. 주 실행 대상은 Linux FPM이지만, 소스에 남은 Windows·CGI·CLI 및 선택 확장 모듈의 보호 누락도 구현 예정으로 추적하며 런타임 범위는 별도로 설명합니다.',
                  '- 공식 GitHub 목록의 모든 페이지를 수집했습니다. CVE 번호가 없는 공지도 GHSA로 보존합니다. 이 목록은 모든 시대의 PHP·운영체제·의존 라이브러리 CVE 전체를 뜻하지 않습니다. 현재 공식 저장소 목록과 명시한 기존 vendor 패치를 완전히 집계한 것입니다.',
                  '', '## 소스와 검증 근거', '']
    else:
        lines += ['', '## Decision rules and scope', '',
                  '- **Resolved:** the relevant implementation is present in this release source. Source evidence and exploit-blocking validation are distinct; `source-only` is not a security runtime pass.',
                  '- **Not applicable:** source and introduction-history evidence show that the specific reported mechanism is absent in PHP 7.0. An old version number or a module omitted from the minimal test binary is insufficient.',
                  '- **Unresolved / planned:** this release receives no credit for the protection. Each row includes investigation, porting and regression work. This does not assert that a newer-PHP exploit works unchanged on PHP 7.0; establishing library/platform reachability is part of planned implementation work.',
                  '- Scope is the complete pinned distribution source. Linux FPM is the primary runtime, but missing protection in included Windows/CGI/CLI and optional-extension code is tracked, with runtime limits stated separately.',
                  '- All pages of the current official GitHub repository catalog were collected, including advisories without CVE identifiers. This is not every historical PHP/OS/dependency CVE ever assigned; it exhausts this catalog snapshot and the named active vendor patches.',
                  '', '## Source and evidence', '']
    lines += ['- Baseline: `' + ledger['baseline'] + '`',
              '- Normalized candidate source SHA-256: `' + ledger['candidate_source_sha256'] + '`',
              '- [Official catalog snapshot](../provenance/security-advisories-20261114.json) · [Reviewed ledger and file hashes](../evidence/security-coverage-20261114.json)',
              '- [Runtime evidence and retained failures](VERIFICATION.md) · [Patch implementation map](PATCH_SCOPE.md)', '']
    lines += [('소스 행 번호는 `patchkit prepare`로 재구성한 위 해시의 소스를 기준으로 합니다. 파일별 해시도 ledger에 기록했습니다. 정상 FPM 시험 36개와 세션 정책 비교는 명시한 동작만 입증하며, 아래 미해결 항목의 공격 차단 시험으로 사용하지 않습니다.' if ko else
               'Source line references address the prepared tree with the digest above, reconstructed by `patchkit prepare`; per-file hashes are recorded in the ledger. The 36 benign FPM checks and paired session-policy comparison establish only their named behavior, not protection against unresolved advisories.'), '',
              ('## 공식 공지 전체 대응표' if ko else '## Complete official advisory matrix'), '',
              ('| 공지 · 대상 | 상태 | 소스 판정 근거 | 예정 작업 · 검증 수준 |' if ko else '| Advisory / component | Status | Source assessment | Planned work / validation |'),
              '|---|---|---|---|']
    for row in ledger['entries']:
        official = by_id[row['ghsa_id']]
        ident = cell(row.get('cve_id') or ('CVE 미배정' if ko else 'No CVE assigned'))
        issue = '[' + row['ghsa_id'] + '](' + row['upstream_url'] + ')'
        title_cell = ident + '<br>' + issue + '<br>' + cell(official['summary']) + '<br>`' + cell(row['component']) + '`'
        evidence = '<br>'.join('`' + code(e) + '`' for e in row['source_evidence'])
        basis = cell(row['reason_' + lang]) + '<br>' + evidence
        if row.get('upstream_fix_url'):
            basis += '<br>[upstream fix](' + row['upstream_fix_url'] + ')'
        for i, url in enumerate(row.get('upstream_comparison', []), 1):
            basis += '<br>[upstream comparison ' + str(i) + '](' + url + ')'
        action = cell(row.get('planned_action_' + lang) or ('추가 구현 없음' if ko else 'No additional implementation'))
        action += '<br>Validation: `' + cell(row['validation']) + '`'
        lines.append('| ' + title_cell + ' | **' + labels[row['status']] + '** | ' + basis + ' | ' + action + ' |')
    lines += ['', ('## 기존 Ubuntu 보안 수정 — 별도 집계' if ko else '## Existing Ubuntu security fixes — separate accounting'), '',
              (f'아래 CVE는 주석 처리되지 않은 활성 vendor 패치에 명시된 {counts["VENDOR_RESOLVED"]}건입니다. 전체 84개 vendor 패치가 모두 CVE 하나씩을 뜻하지는 않습니다. 정확한 공식 소스 아카이브에서 적용했고, 최종 소스의 대응 코드도 대조했습니다. 다중 패치의 중간 코드는 후속 수정으로 대체될 수 있습니다. 기존 소스에 포함된 더 오래된 모든 수정을 이 표가 열거한다고 주장하지 않습니다.' if ko else
               f'These {counts["VENDOR_RESOLVED"]} CVEs are explicitly named by enabled vendor patch filenames. The 84 active vendor patches do not represent 84 distinct CVEs. They were applied from the exact official source archive, and corresponding code was checked in the final source. Intermediate lines in multi-patch fixes can be superseded by follow-up corrections. This does not enumerate every older fix already incorporated in the original source.'), '',
              ('| CVE | 상태와 근거 | 적용 패치 · 최종 소스 |' if ko else '| CVE | Status and provenance | Applied patches / final source |'), '|---|---|---|']
    for row in ledger['vendor_fixes']:
        ident = '[' + row['cve_id'] + '](' + row['upstream_url'] + ')'
        state = ('**해결됨 · vendor 수정 포함**' if ko else '**Resolved · vendor fix present**')
        desc = cell(row['summary']) + '<br>Validation: `vendor-source`'
        patches = '<br>'.join('`' + p['name'] + '`' for p in row['patches'])
        proof = '<br>'.join('`' + code(p) + '`' for p in row['source_evidence'])
        lines.append('| ' + ident + ' | ' + state + '<br>' + desc + ' | ' + patches + '<br>' + proof + ' |')
    lines += ['', ('## 구현 순서와 완료 조건' if ko else '## Implementation order and exit criteria'), '']
    if ko:
        lines += ['1. FPM 입력·상태 출력·접근제어, HTTP 리다이렉트·헤더, TLS 이름 검증과 bcrypt 인증 처리를 먼저 처리합니다.',
                  '2. SOAP·Phar·mysqlnd·pgsql/PDO·이미지·필터·문자열 등 각 선택 기능의 입력 경계와 메모리 수명을 처리합니다. 사용 여부만으로 소스 보호 누락을 없애지 않습니다.',
                  '3. 주 Linux FPM 배포와 별개인 Windows·CGI·개발용 CLI 서버 항목은 해당 플랫폼 시험을 포함한 별도 작업으로 처리합니다.',
                  '4. 각 항목은 공식 수정 대조 → PHP 7.0 이식/보호 구현 → 대상 환경의 격리 회귀검증 → 수정 소스와 결과 해시 공개 후에만 해결됨으로 이동합니다. 원인을 닫지 못한 채 이름만 바꾸거나 기존 실패를 통과로 바꾸지 않습니다.',
                  '', '이번 변경은 대응 현황과 구현 계획의 공개입니다. 예정된 소스 수정이나 추가 서버 배포가 완료됐다는 뜻은 아닙니다.']
    else:
        lines += ['1. Prioritize FPM input/status/access control, HTTP redirects/headers, TLS identity validation and bcrypt authentication.',
                  '2. Address optional SOAP, Phar, mysqlnd, pgsql/PDO, image, filter and string parsing/lifetime protections. Module selection does not erase a source gap.',
                  '3. Track Windows/CGI/development CLI server work separately from the Linux FPM rollout, with platform-specific testing.',
                  '4. Move an item to resolved only after upstream comparison, a PHP 7.0 implementation, isolated target regression, and published source/result identities. Never substitute a renamed status for a closed cause or turn old failures into passes.',
                  '', 'This change publishes coverage and implementation plans. It does not mean planned source fixes or another server deployment have been completed.']
    path = root / ('docs/SECURITY_COVERAGE.ko.md' if ko else 'docs/SECURITY_COVERAGE.md')
    result = '\n'.join(lines) + '\n'
    if args.check:
        if path.read_text() != result:
            raise SystemExit('stale generated coverage document: ' + str(path.relative_to(root)))
    else:
        path.write_text(result)
print('Coverage documents ' + ('match' if args.check else 'rendered') + ' for ' + str(len(by_id)) + ' official advisories.')

for lang, filename in [('en', 'README.md'), ('ko', 'README.ko.md')]:
    ko = lang == 'ko'
    heading = '공식 취약점 대응 현황 — 2026-11-14' if ko else 'Official security coverage — 2026-11-14'
    doc = 'docs/SECURITY_COVERAGE.ko.md' if ko else 'docs/SECURITY_COVERAGE.md'
    intro = (f'공식 PHP 저장소의 공개 공지 **{len(by_id)}건 전체**를 고정 소스와 대조했습니다. 범위와 항목별 근거·예정 작업은 [전체 대응표](' + doc + ')에서 확인하세요.' if ko else
             f'All **{len(by_id)} published official PHP repository advisories** were compared with the pinned source. See the [complete coverage matrix](' + doc + ') for scope, per-item evidence and planned work.')
    summary = ['<!-- SECURITY_COVERAGE_START -->', '## ' + heading, '', intro, '',
               '| ' + ('공식 목록 내 상태 | 건수' if ko else 'Official catalog status | Count') + ' |', '|---|---|',
               '| ' + ('해결됨 · 수정 구현' if ko else 'Resolved · implementation present') + ' | ' + str(counts['RESOLVED']) + ' |',
               '| ' + ('영향 없음 · 해당 결함 경로 부재' if ko else 'Not applicable · reported mechanism absent') + ' | ' + str(counts['NOT_APPLICABLE']) + ' |',
               '| ' + ('미해결 · 검토·구현 예정' if ko else 'Unresolved · review/implementation planned') + ' | ' + str(counts['PLANNED']) + ' |', '',
               (f'기존 Ubuntu vendor 패치로 포함된 **CVE {counts["VENDOR_RESOLVED"]}건은 별도 집계**합니다. 해결됨은 수정 코드가 존재한다는 뜻이며 모든 공격 차단을 실증했다는 뜻은 아닙니다. 미구현 보호는 통과로 표시하지 않습니다. 이 대응표는 현재 공식 GitHub 목록과 명시한 vendor 패치를 대상으로 하며 모든 시대의 PHP·의존 라이브러리 CVE 전체를 뜻하지 않습니다.' if ko else
                f'**{counts["VENDOR_RESOLVED"]} existing vendor-patched CVEs are accounted for separately.** Resolved means protection code is present, not that every exploit was validated. Unimplemented protection is not a pass. The matrix exhausts the current official GitHub catalog and named vendor patches, not every historical PHP/dependency CVE.'),
               '<!-- SECURITY_COVERAGE_END -->']
    if necessity_counts:
        doc = 'docs/IMPLEMENTATION_NECESSITY' + ('.ko' if ko else '') + '.md'
        summary.insert(-1, '')
        summary.insert(-1, (f'기존 51건을 [실제 구현 필요성]({doc})부터 재검토했습니다. 공개 Xenial FPM 기준 **수정 필요 {necessity_counts["REQUIRED"]} / 조건부 {necessity_counts["CONDITIONAL"]} / 다른 OS·SAPI {necessity_counts["OUTSIDE_LINUX_FPM"]} / 해당 경로 없음 {necessity_counts["MECHANISM_ABSENT"]}건**입니다. 먼저 해당 조건을 확인하고 필요한 보호만 구현합니다.' if ko else
                            f'The original 51 items were [reviewed for actual implementation necessity]({doc}): **{necessity_counts["REQUIRED"]} required / {necessity_counts["CONDITIONAL"]} conditional / {necessity_counts["OUTSIDE_LINUX_FPM"]} other OS/SAPI / {necessity_counts["MECHANISM_ABSENT"]} mechanism absent** in the published Xenial FPM scope. Establish prerequisites before implementing relevant protection.'))
    block = '\n'.join(summary) + '\n'
    path = root / filename
    old = path.read_text()
    start = '<!-- SECURITY_COVERAGE_START -->'
    end = '<!-- SECURITY_COVERAGE_END -->'
    if start in old:
        before, tail = old.split(start, 1)
        _, after = tail.split(end, 1)
        new = before + block.rstrip('\n') + after
    else:
        anchor = '## 어떤 문제가 있었고, 무엇을 고쳤나요?' if ko else '## What was wrong, and what is addressed'
        if old.count(anchor) != 1:
            raise ValueError('README coverage insertion anchor is ambiguous')
        new = old.replace(anchor, block + '\n' + anchor, 1)
    if args.check:
        if old != new:
            raise SystemExit('stale README coverage summary: ' + filename)
    else:
        path.write_text(new)
